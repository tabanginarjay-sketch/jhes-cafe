# ==================== PILLAR 1: SECURITY ====================

@pytest.mark.asyncio
async def test_security_headers_present(client):
    """Verify OWASP-recommended security headers are injected into HTTP responses."""
    response = await client.get("/")
    assert response.status_code == 200
    assert response.headers.get("x-content-type-options") == "nosniff"
    assert response.headers.get("x-frame-options") == "DENY"
    assert response.headers.get("x-xss-protection") == "1; mode=block"
    assert response.headers.get("referrer-policy") == "strict-origin-when-cross-origin"


@pytest.mark.asyncio
async def test_rate_limiter_throttles_excessive_requests():
    """Verify sliding-window rate limiter blocks requests exceeding configured threshold."""
    limiter = rate_limiter
    limiter.reset()
    rule = RateLimitRule(max_requests=3, window_seconds=10)
    client_id = "test_ip_123"

    # First 3 requests must be allowed
    for _ in range(3):
        allowed, remaining, _ = limiter.is_allowed(client_id, rule)
        assert allowed is True

    # 4th request must be throttled
    allowed, remaining, retry_after = limiter.is_allowed(client_id, rule)
    assert allowed is False
    assert remaining == 0
    assert retry_after > 0
    assert limiter.get_stats()["total_throttled_requests"] >= 1
    limiter.reset()


def test_row_level_security_enforcement():
    """Verify customers can only access their own records while admins bypass."""
    customer_a = CurrentUser(user_id="usr_111", email="a@cafe.com", role="customer")
    customer_b = CurrentUser(user_id="usr_222", email="b@cafe.com", role="customer")
    admin_user = CurrentUser(user_id="usr_admin", email="admin@cafe.com", role="admin")

    # Customer A accessing their own data -> ALLOWED
    enforce_row_level_security("usr_111", customer_a)

    # Customer B accessing Customer A's data -> FORBIDDEN (403)
    with pytest.raises(HTTPException) as exc_info:
        enforce_row_level_security("usr_111", customer_b)
    assert exc_info.value.status_code == 403

    # Admin accessing Customer A's data -> ALLOWED
    enforce_row_level_security("usr_111", admin_user)


# ==================== PILLAR 3: SPEED (CACHING) ====================

@pytest.mark.asyncio
async def test_cache_manager_operations():
    """Verify TTL caching, cache-aside get_or_set, and prefix invalidation."""
    cache.clear()

    # Set and Get
    cache.set("test:item_1", {"name": "Espresso"}, ttl_seconds=5)
    assert cache.get("test:item_1") == {"name": "Espresso"}

    # Invalidate by prefix
    count = cache.invalidate_prefix("test:")
    assert count == 1
    assert cache.get("test:item_1") is None

    # Cache-aside helper
    calls = 0

    async def fetch_expensive_data():
        nonlocal calls
        calls += 1
        return "expensive_result"

    res1 = await cache.get_or_set("test:computed", fetch_expensive_data, ttl_seconds=10)
    res2 = await cache.get_or_set("test:computed", fetch_expensive_data, ttl_seconds=10)

    assert res1 == "expensive_result"
    assert res2 == "expensive_result"
    assert calls == 1  # Coroutine only executed once due to cache hit!

    stats = cache.get_stats()
    assert stats["hits"] >= 1
    assert stats["hit_ratio_percent"] > 0
    cache.clear()


