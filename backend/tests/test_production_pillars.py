@pytest.mark.asyncio
async def test_correlation_id_propagation(client):
    """Verify X-Request-ID is preserved if provided, or generated and returned if missing."""
    # Case 1: Provided by client
    custom_id = "test-correlation-uuid-999"
    resp1 = await client.get("/", headers={"X-Request-ID": custom_id})
    assert resp1.headers.get("x-request-id") == custom_id

    # Case 2: Generated by server
    resp2 = await client.get("/")
    assert resp2.headers.get("x-request-id") is not None
    assert len(resp2.headers.get("x-request-id")) > 10


